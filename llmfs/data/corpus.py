"""Document streaming, license filtering, and the repository-level split.

See docs/02_data.md §3 (license), §5 (split).

Everything here is a generator over documents. Nothing loads a shard into
memory; a 1 GB shard streams in constant RAM.
"""

from __future__ import annotations

import gzip
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Iterator

import pyarrow.parquet as pq

# docs/02_data.md §3. 57.7% of codeparrot-clean bytes, measured on shard 1.
PERMISSIVE_LICENSES = frozenset({
    "apache-2.0", "mit", "bsd-3-clause", "bsd-2-clause",
    "unlicense", "isc", "cc0-1.0",
})

# 0.5% of repositories (or English documents) go to validation. docs §5.
VAL_PER_10K = 50


@dataclass(frozen=True)
class Doc:
    source: str     # "code" | "en"
    key: str        # what the split is decided on: repo_name for code, doc id for English
    text: str
    uid: str = ""   # stable identity: "<shard file>:<line number>" -- valid because the
                    # dataset revision is pinned. The near-dup drop list refers to these.


def split_of(key: str) -> str:
    """Deterministic train/val assignment from a stable hash of `key`.

    Same key -> same side, every run, every machine, regardless of shard order
    or how many shards are added later. docs/02_data.md §5.

    blake2b, not Python's hash(): the builtin is salted per process
    (PYTHONHASHSEED), so it would give a different split on every run.
    """
    h = int.from_bytes(hashlib.blake2b(key.encode("utf-8"), digest_size=8).digest(), "little")
    return "val" if (h % 10_000) < VAL_PER_10K else "train"


def iter_code_docs(paths: list[Path], split: str | None = None,
                   licenses: frozenset[str] = PERMISSIVE_LICENSES) -> Iterator[Doc]:
    """Stream codeparrot-clean records as Docs.

    split=None yields both sides; "train"/"val" yields one. The license filter
    runs before the split so both sides obey the same allowlist.
    """
    for path in paths:
        with gzip.open(path, "rt", encoding="utf-8") as f:
            for lineno, line in enumerate(f):
                r = json.loads(line)
                if r["license"] not in licenses:
                    continue
                # Upstream already removed autogenerated / line_max>=1000 /
                # alpha_frac<=0.25 files (docs §2), so no further filters here.
                key = r["repo_name"]
                if split is not None and split_of(key) != split:
                    continue
                yield Doc("code", key, r["content"], f"{path.name}:{lineno}")


def iter_en_docs(paths: list[Path], split: str | None = None,
                 batch_rows: int = 2048) -> Iterator[Doc]:
    """Stream fineweb-edu parquet rows as Docs, reading in row batches.

    fineweb-edu is already filtered upstream to int_score >= 3 (raw classifier
    score >= 2.5), so no quality filter here. Split is by document id: there is
    no repo-like grouping to respect.
    """
    for path in paths:
        pf = pq.ParquetFile(path)
        for batch in pf.iter_batches(batch_size=batch_rows, columns=["id", "text"]):
            ids = batch.column("id").to_pylist()
            texts = batch.column("text").to_pylist()
            for key, text in zip(ids, texts):
                if split is not None and split_of(key) != split:
                    continue
                yield Doc("en", key, text)


def code_shards(raw_dir: Path) -> list[Path]:
    return sorted((raw_dir / "codeparrot").glob("file-*.json.gz"))


def en_shards(raw_dir: Path) -> list[Path]:
    return sorted((raw_dir / "fineweb").rglob("*.parquet"))

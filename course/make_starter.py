"""Generate the learner's starter repo from this one. docs/COURSE.md §5.

    uv run python course/make_starter.py                  # -> course/_build/starter/
    uv run python course/make_starter.py --out ../llm-from-scratch-course

Copies every file git tracks, then, for each exercise in course/exercises.py,
replaces the function body with its hint and `raise NotImplementedError`.
The signature, the docstring and everything outside the function stay, so
the learner sees the contract and the shapes but not the answer.

Blanking works on Python's syntax tree, not on markers in the source, so the
stage files never need editing for the course. Comments inside a blanked body
go too, on purpose: in this repo they explain the answer.
"""

from __future__ import annotations

import argparse
import ast
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "course"))
from exercises import MODULES  # noqa: E402

# Files that make sense only for building this project, not for following it.
SKIP = {"CLAUDE.md", "PROGRESS.md"}
MARKER = ".course-starter"          # written into every build, so --out never wipes the wrong folder


def find_function(tree: ast.Module, qualname: str) -> ast.FunctionDef:
    node: ast.AST = tree
    for part in qualname.split("."):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and child.name == part:
                node = child
                break
        else:
            raise SystemExit(f"exercise {qualname!r}: no {part!r} found")
    assert isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)), qualname
    return node


def blank(source: str, qualname: str, hint: str, module: int) -> str:
    """Replace one function's body (everything after its docstring) with the hint."""
    tree = ast.parse(source)
    fn = find_function(tree, qualname)
    body = fn.body
    has_doc = isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
        and isinstance(body[0].value.value, str)
    lines = source.splitlines(keepends=True)
    start = body[0].end_lineno if has_doc else fn.body[0].lineno - 1    # 0-based index of first line to drop
    end = fn.end_lineno                                                  # 1-based, inclusive
    indent = " " * (body[0].col_offset)
    wrapped = textwrap.wrap(hint, width=88 - len(indent) - 2)
    new = [f"{indent}# EXERCISE (module {module}): write this function.\n"]
    new += [f"{indent}# {w}\n" for w in wrapped]
    new.append(f'{indent}raise NotImplementedError("{qualname}: your code here")\n')
    return "".join(lines[:start] + new + lines[end:])


def build(out: Path) -> None:
    if out.exists():
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise SystemExit(f"{out} exists and is not a starter build; refusing to delete it")
        shutil.rmtree(out)
    files = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    for rel in files:
        if rel in SKIP or rel.startswith("course/_build"):
            continue
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, dst)

    # Each exercise re-parses its file, so line numbers stay right after earlier blanks in it.
    n = 0
    for num, mod in MODULES.items():
        for key, hint in mod["exercises"].items():
            path, qualname = key.split("::")
            p = out / path
            p.write_text(blank(p.read_text(), qualname, hint, num))
            n += 1
    for num, mod in MODULES.items():                     # every blanked file must still import-parse
        for key in mod["exercises"]:
            ast.parse((out / key.split("::")[0]).read_text())

    # The production tokenizer (271 KB) ships with the starter: tests and every experiment from
    # module 2 on load it, and retraining it costs an hour (docs/01_tokenizer.md §9). data/ is
    # ignored here, so the starter's .gitignore lets this one folder through.
    tok = out / "data" / "tokenizers" / "split_8192.json"
    tok.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / "data" / "tokenizers" / "split_8192.json", tok)
    gi = (out / ".gitignore").read_text()
    assert "/data/\n" in gi
    (out / ".gitignore").write_text(gi.replace("/data/\n", "/data/*\n!/data/tokenizers/\n"))

    shutil.copy2(ROOT / "course" / "STARTER_README.md", out / "README.md")
    (out / MARKER).write_text("generated by course/make_starter.py; safe to delete and regenerate\n")
    print(f"{out}: {len(files)} files, {n} functions blanked across {len(MODULES)} module(s)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "course" / "_build" / "starter"))
    build(Path(ap.parse_args().out).resolve())
